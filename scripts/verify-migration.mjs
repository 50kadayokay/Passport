// Emits a READ-ONLY verification script for an applied migration.
//
// WHY GENERATED
// -------------
// A hand-written post-deploy checklist is a second source of truth, and this phase
// has already been bitten twice by exactly that: the audit drifted from the
// migration and hid three real defects, and a hardcoded row count went stale the
// moment a fixture changed. So the expectations here are READ OUT OF THE MIGRATION
// FILE -- every column, constraint, index, trigger and function name the migration
// declares becomes something production must show.
//
// It asserts the shape of what was installed. It writes nothing, and it does not
// claim anything about behaviour that only the isolated-schema audit can prove.
//
//   node scripts/verify-migration.mjs 0042 > /tmp/verify.sql
import fs from "node:fs";
import path from "node:path";

const MIGRATIONS = "supabase/migrations";
const which = process.argv[2];
if (!which) { console.error("usage: node scripts/verify-migration.mjs <0042|0043|0044>"); process.exit(2); }

const file = fs.readdirSync(MIGRATIONS).find((f) => f.startsWith(which));
if (!file) { console.error(`no migration starting with ${which}`); process.exit(2); }
const sql = fs.readFileSync(path.join(MIGRATIONS, file), "utf8");

// ---------------------------------------------------------------- extraction
/** Body of `create table [if not exists] public.X (...)`, by paren balancing. */
const tableBody = (src, table) => {
  const head = new RegExp(`create table (?:if not exists )?public\\.${table}\\s*\\(`, "m");
  const m = src.match(head);
  if (!m) return null;
  let i = m.index + m[0].length, depth = 1;
  const start = i;
  while (i < src.length && depth > 0) {
    const c = src[i];
    if (c === "(") depth++; else if (c === ")") depth--;
    i++;
  }
  return src.slice(start, i - 1);
};

const splitTop = (body) => {
  const out = []; let buf = "", d = 0;
  for (const c of body.replace(/--[^\n]*/g, "")) {
    if (c === "(") d++;
    if (c === ")") d--;
    if (c === "," && d === 0) { out.push(buf); buf = ""; continue; }
    buf += c;
  }
  out.push(buf);
  return out.map((x) => x.trim()).filter(Boolean);
};

const tables = [...sql.matchAll(/create table (?:if not exists )?public\.(\w+)/g)].map((m) => m[1]);

const columns = {};      // table -> [{name, generated}]
const constraints = {};   // table -> [names]
for (const t of tables) {
  const body = tableBody(sql, t);
  if (!body) continue;
  columns[t] = []; constraints[t] = [];
  for (const decl of splitTop(body)) {
    const cn = decl.match(/^constraint\s+(\w+)/i);
    if (cn) { constraints[t].push(cn[1]); continue; }
    if (/^(primary key|unique|check|foreign key)\b/i.test(decl)) continue;
    const name = decl.match(/^([a-z_][a-z0-9_]*)\s+\S/i);
    if (name) columns[t].push({ name: name[1], generated: /generated always as/i.test(decl) });
  }
}

const fnNames = [...new Set([...sql.matchAll(/create or replace function public\.(\w+)\s*\(/g)].map((m) => m[1]))];
const idxNames = [...new Set([...sql.matchAll(/create (?:unique )?index (?:if not exists )?(\w+)/g)].map((m) => m[1]))];
const triggerFns = [...new Set([...sql.matchAll(/execute function public\.(\w+)\(\)/g)].map((m) => m[1]))];
const policies = [...new Set([...sql.matchAll(/create policy "?%?I?"?\s*(\w+)?/g)].map((m) => m[1]).filter(Boolean))];
const trigSuffix = /_immutable/.test(sql) ? "_immutable" : null;
const wantsDeleteTrigger = /before update or delete/i.test(sql);
const wantsTruncateTrigger = /before truncate/i.test(sql);

// ---------------------------------------------------------------- emit
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
const L = [];
L.push(`-- =====================================================================`);
L.push(`-- POST-DEPLOY VERIFICATION FOR ${file}`);
L.push(`-- Generated by scripts/verify-migration.mjs from the migration itself.`);
L.push(`-- READ-ONLY. Paste into the SQL Editor after applying the migration.`);
L.push(`-- Every row must read PASS. Any FAIL means production differs from the`);
L.push(`-- audited migration -- stop, do not continue the deployment.`);
L.push(`-- =====================================================================`);
L.push(`with expected_columns(tbl, col, is_generated) as (values`);
const colRows = [];
for (const t of tables) for (const c of columns[t] || []) colRows.push(`  (${lit(t)}, ${lit(c.name)}, ${c.generated})`);
// A migration that creates no tables (0047 only adds a column and policies)
// produced an EMPTY values list here -- `as (values\n\n)` -- which is a syntax
// error, so the whole verification refused to run. Every list now falls back to
// a typed null row, which the queries below already filter out for constraints.
L.push(colRows.length ? colRows.join(",\n") : `  (null::text, null::text, null::boolean)`);
L.push(`),`);
L.push(`expected_constraints(tbl, con) as (values`);
const conRows = [];
for (const t of tables) for (const c of constraints[t] || []) conRows.push(`  (${lit(t)}, ${lit(c)})`);
L.push(conRows.length ? conRows.join(",\n") : `  (null::text, null::text)`);
L.push(`),`);
L.push(`expected_tables(tbl) as (values\n${(tables.length ? tables.map((t) => `  (${lit(t)})`) : ["  (null::text)"]).join(",\n")}\n),`);
L.push(`expected_functions(fn) as (values\n${(fnNames.length ? fnNames : ["__none__"]).map((f) => `  (${lit(f)})`).join(",\n")}\n),`);
L.push(`expected_indexes(idx) as (values\n${(idxNames.length ? idxNames : ["__none__"]).map((i) => `  (${lit(i)})`).join(",\n")}\n),`);

L.push(`
-- 1) every table exists
t_tables as (
  select 'table' as kind, tbl as item,
         case when to_regclass('public.'||tbl) is not null then 'present' else 'MISSING' end as actual,
         (to_regclass('public.'||tbl) is not null) as pass
    from expected_tables where tbl is not null
),
-- 2) every column exists, with the same generated-ness
t_cols as (
  select 'column' as kind, e.tbl||'.'||e.col as item,
         coalesce(case when c.column_name is null then 'MISSING'
                       when (c.is_generated = 'ALWAYS') <> e.is_generated then 'generated='||c.is_generated
                       else 'ok' end, 'MISSING') as actual,
         (c.column_name is not null and (c.is_generated = 'ALWAYS') = e.is_generated) as pass
    from expected_columns e
    left join information_schema.columns c
      on c.table_schema='public' and c.table_name=e.tbl and c.column_name=e.col
   where e.tbl is not null
),
-- 3) no EXTRA columns production has that the migration does not declare
t_extra as (
  select 'extra-column' as kind, c.table_name||'.'||c.column_name as item,
         'PRESENT BUT NOT IN MIGRATION' as actual, false as pass
    from information_schema.columns c
    join expected_tables t on t.tbl = c.table_name and t.tbl is not null
   where c.table_schema='public'
     and not exists (select 1 from expected_columns e where e.tbl=c.table_name and e.col=c.column_name)
),
-- 4) every named constraint exists
t_cons as (
  select 'constraint' as kind, e.tbl||'.'||e.con as item,
         case when x.conname is null then 'MISSING' else x.contype::text end as actual,
         (x.conname is not null) as pass
    from expected_constraints e
    left join (select c.conname, c.contype, t.relname
                 from pg_constraint c join pg_class t on t.oid=c.conrelid
                 join pg_namespace n on n.oid=t.relnamespace where n.nspname='public') x
      on x.conname=e.con and x.relname=e.tbl
   where e.tbl is not null
),
-- 5) every index exists
t_idx as (
  select 'index' as kind, idx as item,
         case when to_regclass('public.'||idx) is null then 'MISSING' else 'present' end as actual,
         (to_regclass('public.'||idx) is not null) as pass
    from expected_indexes where idx <> '__none__'
),
-- 6) every function exists
t_fns as (
  select 'function' as kind, fn as item,
         coalesce((select string_agg(distinct p.prokind::text,',') from pg_proc p
                     join pg_namespace n on n.oid=p.pronamespace
                    where n.nspname='public' and p.proname=fn), 'MISSING') as actual,
         exists (select 1 from pg_proc p join pg_namespace n on n.oid=p.pronamespace
                  where n.nspname='public' and p.proname=fn) as pass
    from expected_functions where fn <> '__none__'
),
-- 7) RLS is enabled on every table
t_rls as (
  select 'rls' as kind, tbl as item,
         coalesce((select case when c.relrowsecurity then 'enabled' else 'DISABLED' end
                     from pg_class c join pg_namespace n on n.oid=c.relnamespace
                    where n.nspname='public' and c.relname=tbl), 'MISSING') as actual,
         coalesce((select c.relrowsecurity from pg_class c join pg_namespace n on n.oid=c.relnamespace
                    where n.nspname='public' and c.relname=tbl), false) as pass
    from expected_tables where tbl is not null
),
-- 8) NO write policy exists on any of them -- writes go through the RPCs only
t_nowrite as (
  select 'no-write-policy' as kind, tbl as item,
         coalesce((select string_agg(cmd, ',') from pg_policies
                    where schemaname='public' and tablename=tbl and cmd <> 'SELECT'), 'none') as actual,
         not exists (select 1 from pg_policies
                      where schemaname='public' and tablename=tbl and cmd <> 'SELECT') as pass
    from expected_tables where tbl is not null
),
-- 9) anon has NO privilege of any kind
t_anon as (
  select 'anon-no-grant' as kind, tbl as item,
         coalesce((select string_agg(distinct privilege_type, ',')
                     from information_schema.role_table_grants
                    where table_schema='public' and table_name=tbl and grantee='anon'), 'none') as actual,
         not exists (select 1 from information_schema.role_table_grants
                      where table_schema='public' and table_name=tbl and grantee='anon') as pass
    from expected_tables where tbl is not null
),
-- 10) authenticated has SELECT and nothing else
t_authed as (
  select 'authenticated-select-only' as kind, tbl as item,
         coalesce((select string_agg(distinct privilege_type, ',' order by privilege_type)
                     from information_schema.role_table_grants
                    where table_schema='public' and table_name=tbl and grantee='authenticated'), 'none') as actual,
         coalesce((select string_agg(distinct privilege_type, ',' order by privilege_type)
                     from information_schema.role_table_grants
                    where table_schema='public' and table_name=tbl and grantee='authenticated'), 'none')
           in ('SELECT','none') as pass
    from expected_tables where tbl is not null
)`);

if (trigSuffix) {
  L.push(`,
-- 11) append-only trigger fires on ${wantsDeleteTrigger ? "UPDATE *and* DELETE" : "UPDATE"}
t_trig as (
  select 'append-only-trigger' as kind, e.tbl as item,
         coalesce((select case when bool_or((tg.tgtype & 16) > 0) and bool_or((tg.tgtype & 8) > 0) then 'update+delete'
                               when bool_or((tg.tgtype & 16) > 0) then 'UPDATE ONLY'
                               else 'other' end
                     from pg_trigger tg join pg_class c on c.oid=tg.tgrelid
                     join pg_namespace n on n.oid=c.relnamespace
                    where n.nspname='public' and c.relname=e.tbl and not tg.tgisinternal), 'MISSING') as actual,
         coalesce((select bool_or((tg.tgtype & 16) > 0) ${wantsDeleteTrigger ? "and bool_or((tg.tgtype & 8) > 0)" : ""}
                     from pg_trigger tg join pg_class c on c.oid=tg.tgrelid
                     join pg_namespace n on n.oid=c.relnamespace
                    where n.nspname='public' and c.relname=e.tbl and not tg.tgisinternal), false) as pass
    from expected_tables e where e.tbl is not null
)`);
}

if (wantsTruncateTrigger) {
  L.push(`,
-- 12) TRUNCATE guard. TRUNCATE is restricted by neither RLS nor row triggers, so
--     the row-level guard above does not cover it.
t_trunc as (
  select 'truncate-guard' as kind, e.tbl as item,
         coalesce((select string_agg(tg.tgname, ',') from pg_trigger tg
                     join pg_class c on c.oid=tg.tgrelid
                     join pg_namespace n on n.oid=c.relnamespace
                    where n.nspname='public' and c.relname=e.tbl and not tg.tgisinternal
                      and (tg.tgtype & 32) > 0), 'MISSING') as actual,
         exists (select 1 from pg_trigger tg join pg_class c on c.oid=tg.tgrelid
                   join pg_namespace n on n.oid=c.relnamespace
                  where n.nspname='public' and c.relname=e.tbl and not tg.tgisinternal
                    and (tg.tgtype & 32) > 0) as pass
    from expected_tables e where e.tbl is not null
)`);
}

const unions = ["t_tables", "t_cols", "t_extra", "t_cons", "t_idx", "t_fns", "t_rls", "t_nowrite", "t_anon", "t_authed"];
if (trigSuffix) unions.push("t_trig");
if (wantsTruncateTrigger) unions.push("t_trunc");

L.push(`
select kind, item, actual, case when pass then 'PASS' else '*** FAIL ***' end as result
  from (${unions.map((u) => `select * from ${u}`).join(" union all ")}) z
 union all
select '~~ SUMMARY ~~', 'checks', count(*)::text, '' from (${unions.map((u) => `select * from ${u}`).join(" union all ")}) s
 union all
select '~~ SUMMARY ~~', 'FAILED', count(*) filter (where not pass)::text,
       case when count(*) filter (where not pass) = 0 then 'clean' else '*** STOP: DO NOT CONTINUE ***' end
  from (${unions.map((u) => `select * from ${u}`).join(" union all ")}) s2
 order by 1, 2;`);

console.log(L.join("\n"));
